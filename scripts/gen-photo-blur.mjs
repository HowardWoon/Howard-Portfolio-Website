#!/usr/bin/env node
/**
 * R17 F-05: generates components/photo-blur.ts, a map from every gallery photo (src) to a tiny 16 px wide blurred
 * WebP data URL used as next/image `blurDataURL`, so a print shows a soft preview of its photo instead of an empty
 * cream box while the real image loads. Re-run after adding or replacing a gallery photo:
 *   node scripts/gen-photo-blur.mjs
 * Uses `sharp`, which ships with Next.js (no new dependency). Reads the photo lists from the two gallery sources.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const sources = ['components/interactive-photo-stack.tsx', 'components/stacked-projects.tsx'];
const srcs = [
  ...new Set(
    sources.flatMap((f) => [...readFileSync(f, 'utf8').matchAll(/src: '(\/images\/[^']+)'/g)].map((m) => m[1])),
  ),
].sort();

const lines = [];
for (const src of srcs) {
  const buf = await sharp(`public${src}`).resize(16).blur(0.6).webp({ quality: 40 }).toBuffer();
  lines.push(`  '${src}': 'data:image/webp;base64,${buf.toString('base64')}',`);
}

writeFileSync(
  'components/photo-blur.ts',
  `// Generated by scripts/gen-photo-blur.mjs (R17 F-05). Do not edit by hand: re-run the script after changing a photo.
export const PHOTO_BLUR: Record<string, string> = {
${lines.join('\n')}
};
`,
);
console.log(`photo-blur: ${lines.length} photos`);
