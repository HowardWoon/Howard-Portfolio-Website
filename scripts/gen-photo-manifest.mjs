#!/usr/bin/env node
/**
 * R102 (owner: "when I upload new photos, set a rule ... auto update, plan it yourself, put the photos in yourself"):
 * writes lib/photo-manifest.ts, the REAL pixel size (sharp().metadata(), AGENTS.md 6.2) of every photo in the photo
 * folders below. components/memory-data.ts reads it, so a photo dropped into a gallery's folder joins that gallery's
 * memory chapter (Memory Reel, The Build's film reels) without anyone typing its size. Runs before every build
 * (package.json "prebuild") and by hand: node scripts/gen-photo-manifest.mjs
 * Uses `sharp`, which ships with Next.js (no new dependency).
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

/** the folders that hold gallery / event photos (logos, story art, the Doom frames and portraits are not memories) */
export const PHOTO_DIRS = ['images/projects', 'images/experience', 'images/experiences', 'images/muba'];

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(jpe?g|png|webp)$/i.test(f) ? [p] : [];
  });

const files = PHOTO_DIRS.flatMap((d) => walk(join('public', d)))
  .map((p) => '/' + p.replace(/\\/g, '/').replace(/^public\//, ''))
  .sort();

const lines = [];
for (const src of files) {
  const m = await sharp(`public${src}`).metadata();
  // a phone photo can carry an EXIF rotation: the browser shows it turned, so its shown size is swapped
  const turned = (m.orientation ?? 1) >= 5;
  const [w, h] = turned ? [m.height, m.width] : [m.width, m.height];
  lines.push(`  '${src}': [${w}, ${h}],`);
}

// formatted like every other file (the pre-commit check), so a build never leaves an unformatted change behind
const prettier = require('prettier');
const target = 'lib/photo-manifest.ts';
const text = `// Generated by scripts/gen-photo-manifest.mjs (R102). Do not edit by hand: it runs before every build.
export const PHOTO_MANIFEST: Record<string, [number, number]> = {
${lines.join('\n')}
};
`;
writeFileSync(target, await prettier.format(text, { ...(await prettier.resolveConfig(target)), filepath: target }));
console.log(`photo manifest: ${files.length} photos`);
